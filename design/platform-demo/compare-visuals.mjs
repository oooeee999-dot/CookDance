import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
const folder = path.join(process.cwd(), 'design', 'platform-demo');
const source = path.join(folder, 'visual-target.png');
await fs.access(source);
const prototype = path.join(folder, '07-photo-wall-final-1440.jpg');
const sourceMeta = await sharp(source).metadata();
const prototypeMeta = await sharp(prototype).metadata();
const normalizedSource = await sharp(source).resize({ width: 1440 }).toBuffer();
const sourceView = await sharp(normalizedSource).extract({ left: 0, top: 0, width: 1440, height: 900 }).jpeg({ quality: 90 }).toBuffer();
const implementationView = await sharp(prototype).resize(1440, 900, { fit: 'fill' }).jpeg({ quality: 90 }).toBuffer();
await sharp({ create: { width: 2880, height: 900, channels: 3, background: '#faf9f6' } }).composite([{ input: sourceView, left: 0, top: 0 }, { input: implementationView, left: 1440, top: 0 }]).jpeg({ quality: 90 }).toFile(path.join(folder, 'design-qa-comparison.jpg'));
const sourceHeader = await sharp(sourceView).extract({ left: 0, top: 0, width: 1440, height: 150 }).toBuffer();
const implementationHeader = await sharp(implementationView).extract({ left: 0, top: 0, width: 1440, height: 150 }).toBuffer();
await sharp({ create: { width: 1440, height: 300, channels: 3, background: '#faf9f6' } }).composite([{ input: sourceHeader, left: 0, top: 0 }, { input: implementationHeader, left: 0, top: 150 }]).jpeg({ quality: 92 }).toFile(path.join(folder, 'design-qa-header.jpg'));
const mobilePath = path.join(folder, '09-photo-wall-mobile-full.jpg');
const mobileMeta = await sharp(mobilePath).metadata();
await sharp(mobilePath).extract({ left: 0, top: 0, width: mobileMeta.width, height: Math.min(844, mobileMeta.height) }).jpeg({ quality: 90 }).toFile(path.join(folder, '08-photo-wall-mobile-390.jpg'));
console.log(JSON.stringify({ source: [sourceMeta.width, sourceMeta.height], prototype: [prototypeMeta.width, prototypeMeta.height], mobile: [mobileMeta.width, mobileMeta.height], comparison: '2880x900; source left, prototype right' }));
